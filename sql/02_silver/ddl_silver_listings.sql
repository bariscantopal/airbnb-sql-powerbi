IF OBJECT_ID('silver.listings') IS NOT NULL DROP TABLE silver.listings;
CREATE TABLE silver.listings (
    listing_id                   BIGINT        NOT NULL PRIMARY KEY,
    listing_name                 NVARCHAR(300) NULL,
    scraped_date                 DATE          NULL,
    host_id                      BIGINT        NULL,
    host_tenure_months           INT           NULL,
    is_superhost                 BIT           NULL,
    host_identity_verified       BIT           NULL,
    calculated_host_listings     INT           NULL,
    neighbourhood                NVARCHAR(200) NULL,
    latitude                     DECIMAL(9,6)  NULL,
    longitude                    DECIMAL(9,6)  NULL,
    property_type                NVARCHAR(100) NULL,
    room_type                    NVARCHAR(50)  NULL,
    accommodates                 INT           NULL,
    bedrooms                     INT           NULL,
    beds                         INT           NULL,
    bathrooms                    DECIMAL(4,1)  NULL,
    bathrooms_is_shared          BIT           NULL,
    price                        DECIMAL(12,2) NULL,
    minimum_nights               INT           NULL,
    maximum_nights               INT           NULL,
    has_availability             BIT           NULL,
    availability_30              INT           NULL,
    availability_90              INT           NULL,
    availability_365             INT           NULL,
    number_of_reviews            INT           NULL,
    number_of_reviews_ltm        INT           NULL,
    first_review                 DATE          NULL,
    last_review                  DATE          NULL,
    reviews_per_month            DECIMAL(6,2)  NULL,
    review_scores_rating         DECIMAL(4,2)  NULL,
    review_scores_accuracy       DECIMAL(4,2)  NULL,
    review_scores_cleanliness    DECIMAL(4,2)  NULL,
    review_scores_checkin        DECIMAL(4,2)  NULL,
    review_scores_communication  DECIMAL(4,2)  NULL,
    review_scores_location       DECIMAL(4,2)  NULL,
    review_scores_value          DECIMAL(4,2)  NULL,
    license_status               NVARCHAR(20)  NULL,
    is_price_outlier             BIT           NOT NULL DEFAULT 0,
    is_active                    BIT           NOT NULL DEFAULT 0,
    is_long_min_stay             BIT           NOT NULL DEFAULT 0,
    dwh_load_date                DATETIME2     NOT NULL DEFAULT SYSDATETIME()
);
GO